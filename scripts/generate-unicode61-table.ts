import { Database } from "bun:sqlite";

// Generates src/shared/unicode61Table.ts from SQLite's own FTS5 `unicode61 remove_diacritics 2`
// tokenizer, so the in-memory search tokenizer (src/shared/searchText.ts) treats every code point
// exactly as `messages_fts` does. tests/phase6-search.test.ts re-reads SQLite and fails if the
// committed table drifts. Run: bun scripts/generate-unicode61-table.ts

export const FTS_TOKENIZER = "unicode61 remove_diacritics 2";

/** Run values besides fold deltas: the code point separates tokens, or is dropped from its token. */
export const SEPARATOR = 0x200000;
export const DROPPED = 0x200001;

export interface Unicode61Runs {
  readonly starts: ReadonlyArray<number>;
  readonly values: ReadonlyArray<number>;
}

const isSurrogate = (codePoint: number) => codePoint >= 0xd800 && codePoint <= 0xdfff;

/**
 * Tokenizes `a<c>a` for every code point c: two tokens mean c separates, `aa` means c is dropped,
 * and `a<f>a` means c folds to f. Consecutive code points with the same value form one run.
 */
export const readUnicode61Runs = (): Unicode61Runs => {
  const database = new Database(":memory:");
  try {
    database.exec(`
      CREATE VIRTUAL TABLE probe USING fts5(text, tokenize = '${FTS_TOKENIZER}');
      CREATE VIRTUAL TABLE probe_terms USING fts5vocab(probe, 'instance');
    `);
    const insert = database.prepare("INSERT INTO probe (rowid, text) VALUES (?, ?)");
    database.transaction(() => {
      for (let codePoint = 1; codePoint <= 0x10ffff; codePoint += 1) {
        if (!isSurrogate(codePoint)) insert.run(codePoint, `a${String.fromCodePoint(codePoint)}a`);
      }
    })();
    const terms = new Map<number, string[]>();
    for (const row of database.prepare("SELECT doc, term FROM probe_terms ORDER BY doc, offset").all() as Array<{ doc: number; term: string }>) {
      const list = terms.get(row.doc);
      if (list) list.push(row.term);
      else terms.set(row.doc, [row.term]);
    }

    const starts: number[] = [0];
    const values: number[] = [SEPARATOR];
    for (let codePoint = 1; codePoint <= 0x10ffff; codePoint += 1) {
      let value = SEPARATOR;
      if (!isSurrogate(codePoint)) {
        const tokens = terms.get(codePoint) ?? [];
        const chars = tokens.length === 1 ? [...tokens[0]!] : [];
        if (tokens.length === 2 && tokens[0] === "a" && tokens[1] === "a") value = SEPARATOR;
        else if (chars.length === 2) value = DROPPED;
        else if (chars.length === 3) value = chars[1]!.codePointAt(0)! - codePoint;
        else throw new Error(`Unexpected tokens for U+${codePoint.toString(16)}: ${JSON.stringify(tokens)}`);
      }
      if (value !== values[values.length - 1]) {
        starts.push(codePoint);
        values.push(value);
      }
    }
    return { starts, values };
  } finally {
    database.close();
  }
};

const chunk = (numbers: ReadonlyArray<number>) => {
  const lines: string[] = [];
  for (let index = 0; index < numbers.length; index += 24) lines.push(`  ${numbers.slice(index, index + 24).join(",")},`);
  return lines.join("\n");
};

export const renderUnicode61Table = (runs: Unicode61Runs): string => `// Generated by scripts/generate-unicode61-table.ts from SQLite FTS5 '${FTS_TOKENIZER}'. Do not edit.
// Run i covers code points [RUN_STARTS[i], RUN_STARTS[i + 1]). Its value is ${SEPARATOR} (separator),
// ${DROPPED} (dropped from the token, e.g. combining accents), or the delta to the folded code point.

export const RUN_STARTS: ReadonlyArray<number> = [
${chunk(runs.starts)}
];

export const RUN_VALUES: ReadonlyArray<number> = [
${chunk(runs.values)}
];
`;

if (import.meta.main) {
  const path = new URL("../src/shared/unicode61Table.ts", import.meta.url).pathname;
  const runs = readUnicode61Runs();
  await Bun.write(path, renderUnicode61Table(runs));
  console.log(`Wrote ${runs.starts.length} runs to ${path}`);
}
